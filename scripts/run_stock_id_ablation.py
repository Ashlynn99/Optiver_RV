"""Run matched grouped-CV experiments with and without stock_id.

This script requires the engineered training cache produced by the notebook.
It does not download or redistribute the Kaggle competition data.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from src.experiment import run_grouped_lightgbm_cv


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--train-features",
        type=Path,
        required=True,
        help="Path to train_base_features.parquet generated by the notebook.",
    )
    parser.add_argument("--output", type=Path, default=Path("reports/stock_id_ablation.csv"))
    parser.add_argument("--folds", type=int, default=5)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    train = pd.read_parquet(args.train_features)
    variants = [
        (True, True),
        (False, True),
        (False, False),
    ]
    results = [
        run_grouped_lightgbm_cv(
            train,
            n_splits=args.folds,
            include_stock_id=include_stock_id,
            include_stock_context=include_stock_context,
        )
        for include_stock_id, include_stock_context in variants
    ]

    rows = []
    for result in results:
        rows.append(
            {
                "variant": result.label,
                "folds": len(result.fold_scores),
                "feature_count": len(result.feature_columns),
                "oof_rmspe": result.oof_rmspe,
            }
        )
    output = pd.DataFrame(rows)
    output["relative_change_vs_full_model"] = (
        output["oof_rmspe"] / output.loc[0, "oof_rmspe"] - 1
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    output.to_csv(args.output, index=False)
    print(output.to_string(index=False))
    print(f"saved: {args.output}")


if __name__ == "__main__":
    main()
